const CONTROLLER_CONFLICT_CODES = new Set([
  "GIT_CONTROLLER_ACCEPTED_CAS_FAILED",
  "GIT_CONTROLLER_IDEMPOTENCY_CONFLICT",
  "GIT_CONTROLLER_REMOTE_HISTORY_ADMIN_APPROVAL_REQUIRED",
  "GIT_CONTROLLER_REMOTE_HISTORY_ADMIN_REVIEW_REQUIRED",
  "GIT_CONTROLLER_REMOTE_HISTORY_IMPACT_UNKNOWN",
  "GIT_CONTROLLER_REMOTE_CHANGED",
  "STORY_BASELINE_RESTRICTED_EXECUTOR_REQUIRED",
  "STORY_REPOSITORY_EXACT_SHA_CONFLICT",
]);

const CONTROLLER_CLIENT_ERROR_CODES = new Set([
  "GIT_CONTROLLER_BRANCH_NOT_ALLOWED",
  "GIT_CONTROLLER_BRANCH_REQUIRED",
  "GIT_CONTROLLER_COMMAND_FIELD_INVALID",
  "GIT_CONTROLLER_COMMAND_FIELD_REJECTED",
  "GIT_CONTROLLER_COMMAND_FIELD_REQUIRED",
  "GIT_CONTROLLER_HOOKS_ACTION_INVALID",
  "GIT_CONTROLLER_IDEMPOTENCY_KEY_REQUIRED",
  "GIT_CONTROLLER_IDEMPOTENCY_MISMATCH",
  "GIT_CONTROLLER_INVALID_BRANCH",
  "GIT_CONTROLLER_INVALID_REMOTE",
  "GIT_CONTROLLER_INVALID_SHA",
  "GIT_CONTROLLER_REMOTE_INVALID",
  "GIT_CONTROLLER_REQUEST_FIELDS_REJECTED",
  "STORY_BASELINE_STRATEGY_REJECTED",
]);

const CONTROLLER_UPSTREAM_TRUST_CODES = new Set([
  "GIT_CONTROLLER_ATTESTATION_MISMATCH",
  "GIT_CONTROLLER_RESPONSE_SIGNATURE_INVALID",
  "GIT_CONTROLLER_RESPONSE_UNSIGNED",
]);

const CONTROLLER_INTEGRITY_CODES = new Set([
  "GIT_CONTROLLER_FETCHED_SHA_MISMATCH",
  "GIT_CONTROLLER_HOOKS_MANIFEST_MISMATCH",
  "GIT_CONTROLLER_MIRROR_STATE_CORRUPT",
  "GIT_CONTROLLER_OBJECT_FORMAT_MISMATCH",
]);

export function controllerErrorStatus(error) {
  const code = String(error?.code || "");
  if (code === "GIT_CONTROLLER_AUTH_REQUIRED") return 401;
  if (code === "GIT_CONTROLLER_ADMIN_REQUIRED") return 403;
  if (
    /(?:REMOTE|BASE|REPOSITORY|LOGICAL_REPOSITORY)_NOT_REGISTERED$/.test(code)
    || /STORY_CONTEXT_NOT_FOUND$/.test(code)
  ) return 404;
  // A malformed or unverifiable response from the privileged Controller is an
  // upstream trust-boundary failure, never a caller input error.
  if (CONTROLLER_UPSTREAM_TRUST_CODES.has(code)) return 502;
  // Integrity checks performed inside the Controller indicate a server-side
  // invariant failure. In particular, do not let generic MISMATCH/INVALID
  // wording turn these into HTTP 400.
  if (
    CONTROLLER_INTEGRITY_CODES.has(code)
    || /(?:^|_)(?:INTEGRITY_FAILED|STATE_CORRUPT)$/.test(code)
    || /(?:^|_)INTERNAL_(?:CONFLICT|ERROR|FAILED)$/.test(code)
  ) return 500;
  if (
    CONTROLLER_CONFLICT_CODES.has(code)
    || /PREVIEW_|LEASE_|BLOCKED|STALE|EXPECTED_HEAD_CHANGED|REMOTE_HISTORY_REJECTED|OPERATION_IN_PROGRESS|RECOVERY_REQUIRED/.test(code)
    || /(?:_CAS_FAILED|_CONFLICT|_RACE|_DRIFT|_DRIFTED|_CHANGED)$/.test(code)
  ) return 409;
  if (/AUTH|CREDENTIAL/.test(code)) return 502;
  if (CONTROLLER_CLIENT_ERROR_CODES.has(code)) return 400;
  return 500;
}
